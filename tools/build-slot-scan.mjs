import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(resolve(root, path), 'utf8').replaceAll('\r\n', '\n');
const entry = read('slot-scan.lua');
const marker = /-- SCANNER_MODULE_BEGIN\n[\s\S]*?-- SCANNER_MODULE_END/;
if (entry.match(/-- SCANNER_MODULE_BEGIN/g)?.length !== 1 || !marker.test(entry)) throw Error('Scanner entry changed');
const output = '-- Generated by tools/build-slot-scan.mjs. One download; no mutable module fetch.\n'
  + entry.replace(marker, () => 'local Scan = (function()\n' + read('control/menu-scan.lua') + '\nend)()');
const path = 'dist/slot-scan.lua';
if (process.argv.includes('--check')) {
  if (read(path) !== output) throw Error('Rebuild stale scanner');
  console.log('Standalone scanner matches source');
} else {
  mkdirSync(resolve(root, 'dist'), { recursive: true });
  writeFileSync(resolve(root, path), output);
  console.log('Built standalone scanner: ' + Buffer.byteLength(output) + ' bytes');
}
